// 받침 위치 자음 빈도 (받침이 되거나 다음 음절 초성이 될 수 있음)
export const BATCHIM_FREQ = {
  'ㄴ': 26, 'ㅇ': 17, 'ㄹ': 14, 'ㄱ': 10, 'ㅁ': 8, 'ㅅ': 6,
  'ㅂ': 5, 'ㅆ': 4, 'ㄷ': 3, 'ㅈ': 2, 'ㅎ': 2, 'ㅊ': 1.5,
  'ㅋ': 0.8, 'ㅌ': 0.8, 'ㅍ': 0.8, 'ㄲ': 0.5,
};

// 받침 상태(모음까지 입력된 상태)에서 자음을 고를 때:
// 받침 빈도 60% + 다음 음절 초성 빈도 40% 혼합
export function batchimBlend() {
  const out = {};
  const keys = new Set([...Object.keys(CHO_FREQ), ...Object.keys(BATCHIM_FREQ)]);
  for (const k of keys) {
    out[k] = 0.6 * (BATCHIM_FREQ[k] ?? 0) + 0.4 * (CHO_FREQ[k] ?? 0);
  }
  return out;
}
